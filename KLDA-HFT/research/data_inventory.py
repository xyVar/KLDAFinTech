#!/usr/bin/env python3
"""
RESEARCH LANE — Data inventory (read-only).

Answers: how much tick history do we have per symbol, and which symbols
have too little data to support the conditional-pattern sweep gate
(>=100 in-sample occurrences AND >=100 out-of-sample occurrences).

Writes reports/data_inventory_<date>.md and .json (repo root /reports).
Makes NO writes to the database: the session is forced read-only at
connection time, so any accidental write statement would error.

Run on the machine that hosts the DB:
    python KLDA-HFT/research/data_inventory.py
"""

import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

import psycopg2

REPO_ROOT = Path(__file__).resolve().parents[2]
REPORTS_DIR = REPO_ROOT / "reports"

# Hard-won constraint (docs/PROTOCOL.md): host must be 127.0.0.1, never
# localhost — ::1 can be claimed by a WSL postgres relay with other creds.
DB_CONFIG = {
    "host": "127.0.0.1",
    "port": 5432,
    "database": "KLDA-HFT_Database",
    "user": "postgres",
    "password": os.environ.get("KLDA_DB_PASSWORD", "MyKldaTechnologies2025!"),
    "connect_timeout": 10,
}

# Sufficiency thresholds for the sweep.
# Rationale: intra-day patterns fire a handful of times/day/symbol at most;
# the gate needs >=100 IS + >=100 OOS occurrences per condition cell.
MIN_DAYS_SUFFICIENT = 60      # full green light
MIN_DAYS_MARGINAL = 25        # testable for high-frequency patterns only
MIN_TICKS_SUFFICIENT = 2_000_000


def connect_readonly():
    conn = psycopg2.connect(
        options="-c default_transaction_read_only=on -c statement_timeout=900000",
        **DB_CONFIG,
    )
    conn.autocommit = True
    return conn


def main():
    try:
        conn = connect_readonly()
    except Exception as e:
        sys.exit(f"Cannot reach DB (is Postgres up? host must be 127.0.0.1): {e}")

    cur = conn.cursor()
    cur.execute(
        """
        SELECT symbol,
               COUNT(*)                            AS n_ticks,
               MIN(time)                           AS first_tick,
               MAX(time)                           AS last_tick,
               COUNT(DISTINCT time::date)          AS n_days,
               percentile_cont(0.5) WITHIN GROUP (ORDER BY (ask - bid)) AS med_spread_abs
        FROM ticks
        GROUP BY symbol
        ORDER BY n_ticks DESC
        """
    )
    rows = cur.fetchall()
    conn.close()

    today = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    REPORTS_DIR.mkdir(exist_ok=True)

    inventory = []
    for sym, n_ticks, first, last, n_days, med_spread in rows:
        if n_days >= MIN_DAYS_SUFFICIENT and n_ticks >= MIN_TICKS_SUFFICIENT:
            status = "SUFFICIENT"
        elif n_days >= MIN_DAYS_MARGINAL:
            status = "MARGINAL (high-frequency patterns only; gap-fill & daily patterns cannot reach n>=100)"
        else:
            status = "INSUFFICIENT — too little data for any gated test"
        inventory.append({
            "symbol": sym,
            "n_ticks": int(n_ticks),
            "first_tick": str(first),
            "last_tick": str(last),
            "distinct_days": int(n_days),
            "median_abs_spread": float(med_spread) if med_spread is not None else None,
            "status": status,
        })

    md = [
        f"# Data Inventory — {today}",
        "",
        f"Source: `ticks` hypertable, read-only session. Generated by `KLDA-HFT/research/data_inventory.py`.",
        "",
        f"Sufficiency gate context: the pattern sweep needs >=100 IS and >=100 OOS",
        f"occurrences per condition cell. Thresholds: SUFFICIENT >= {MIN_DAYS_SUFFICIENT} days and",
        f">= {MIN_TICKS_SUFFICIENT:,} ticks; MARGINAL >= {MIN_DAYS_MARGINAL} days.",
        "",
        "| Symbol | Ticks | Days | First | Last | Median spread (abs) | Status |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in inventory:
        md.append(
            f"| {r['symbol']} | {r['n_ticks']:,} | {r['distinct_days']} "
            f"| {r['first_tick'][:16]} | {r['last_tick'][:16]} "
            f"| {r['median_abs_spread']} | {r['status']} |"
        )
    insufficient = [r["symbol"] for r in inventory if r["status"].startswith("INSUFFICIENT")]
    marginal = [r["symbol"] for r in inventory if r["status"].startswith("MARGINAL")]
    md += [
        "",
        f"**Symbols with too little data:** {', '.join(insufficient) if insufficient else 'none'}",
        f"**Marginal symbols:** {', '.join(marginal) if marginal else 'none'}",
        "",
        "Note on honesty: a symbol below threshold yields the verdict INSUFFICIENT_N,",
        "which is *not* a pattern failure — it is an untested pattern. Only a tested",
        "pattern that misses the gate is a FAIL.",
    ]

    md_path = REPORTS_DIR / f"data_inventory_{today}.md"
    json_path = REPORTS_DIR / f"data_inventory_{today}.json"
    md_path.write_text("\n".join(md), encoding="utf-8")
    json_path.write_text(json.dumps(inventory, indent=2), encoding="utf-8")

    print("\n".join(md))
    print(f"\nWritten: {md_path}\nWritten: {json_path}")


if __name__ == "__main__":
    main()
